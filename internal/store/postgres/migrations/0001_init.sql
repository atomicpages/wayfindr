-- Initial schema (docs/internal/design.md §5): the SQLite schema with uuid, bytea,
-- timestamptz, and vector columns. schema_version is owned by the migration
-- runner in internal/store.

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE users (
  id         uuid PRIMARY KEY,                -- UUIDv7, generated by the store
  created_at timestamptz NOT NULL DEFAULT now()
);

-- tool_definition parses a stored definition. It returns NULL instead of
-- failing on bytes jsonb refuses (such as a \u0000 escape), so an odd tool
-- only loses its search text instead of failing the whole catalog write.
-- It is IMMUTABLE because a database's encoding never changes.
CREATE FUNCTION tool_definition(definition bytea) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE AS $$
BEGIN
  RETURN convert_from(definition, 'UTF8')::jsonb;
EXCEPTION WHEN others THEN
  RETURN NULL;
END
$$;

-- tool_title mirrors store.NewTool: title, falling back to annotations.title.
CREATE FUNCTION tool_title(definition bytea) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT coalesce(nullif(d->>'title', ''), d->'annotations'->>'title', '')
  FROM (SELECT tool_definition(definition) AS d) AS parsed
$$;

-- search_words splits identifiers the way the tokenizer does (design §7.5):
-- camelCase boundaries and every run of non-alphanumerics become spaces.
CREATE FUNCTION search_words(t text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT regexp_replace(regexp_replace(t, '([[:lower:][:digit:]])([[:upper:]])', '\1 \2', 'g'),
                        '[^[:alnum:]]+', ' ', 'g')
$$;

-- tool_params returns inputSchema.properties, or an empty object when the
-- definition has none (jsonb_each fails on anything but an object).
CREATE FUNCTION tool_params(d jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT CASE WHEN jsonb_typeof(d->'inputSchema'->'properties') = 'object'
              THEN d->'inputSchema'->'properties' ELSE '{}'::jsonb END
$$;

-- tool_search_text weights the fields like the SQLite index (design §7.5):
-- A qualified name, B title, C parameter names, D description and parameter
-- descriptions.
CREATE FUNCTION tool_search_text(connector text, name text, definition bytea) RETURNS tsvector
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
  SELECT
    setweight(to_tsvector('simple', search_words(connector || '.' || name)), 'A') ||
    setweight(to_tsvector('simple', search_words(tool_title(definition))), 'B') ||
    setweight(to_tsvector('simple', search_words(coalesce(
      (SELECT string_agg(p.key, ' ') FROM jsonb_each(tool_params(d)) AS p), ''))), 'C') ||
    setweight(to_tsvector('simple', search_words(coalesce(d->>'description', '') || ' ' || coalesce(
      (SELECT string_agg(p.value->>'description', ' ') FROM jsonb_each(tool_params(d)) AS p), ''))), 'D')
  FROM (SELECT tool_definition(definition) AS d) AS parsed
$$;

CREATE TABLE tools (
  user_id         uuid NOT NULL REFERENCES users(id),
  connector       text NOT NULL,
  name            text NOT NULL,              -- upstream (unqualified) tool name
  definition      bytea NOT NULL,             -- mcp.Tool JSON exactly as received
  content_hash    bytea NOT NULL,             -- sha256(embed text)
  embedding       vector,                     -- NULL until embedded; dimensions vary by model
  embedding_model text,                       -- model identity that produced `embedding`
  updated_at      timestamptz NOT NULL,
  qualified_name  text GENERATED ALWAYS AS (connector || '.' || name) STORED,
  title           text GENERATED ALWAYS AS (tool_title(definition)) STORED,
  search_text     tsvector GENERATED ALWAYS AS (tool_search_text(connector, name, definition)) STORED,
  PRIMARY KEY (user_id, connector, name)
);

CREATE INDEX tools_search_text ON tools USING gin (search_text);
CREATE INDEX tools_name_trgm ON tools USING gin (qualified_name gin_trgm_ops, title gin_trgm_ops);

CREATE TABLE connector_sync (
  user_id      uuid NOT NULL,
  connector    text NOT NULL,
  last_sync_at timestamptz,
  last_error   text,
  PRIMARY KEY (user_id, connector)
);

CREATE TABLE credentials (
  user_id          uuid NOT NULL,
  connector        text NOT NULL,
  resource         text NOT NULL,             -- canonical MCP URL the tokens are bound to (RFC 8707)
  issuer           text,                      -- authorization server issuer
  redirect_uri     text,                      -- URI the DCR client was registered with
  dcr_client_id    text,                      -- set only when obtained via DCR
  dcr_client       bytea,                     -- sealed: DCR client_secret + registration response
  token            bytea,                     -- sealed: {access, refresh, type, expiry}
  granted_scopes   text,
  requested_scopes text,                      -- includes step-up additions
  updated_at       timestamptz NOT NULL,
  PRIMARY KEY (user_id, connector)
);

CREATE TABLE secrets (
  user_id    uuid NOT NULL,
  name       text NOT NULL,
  value      bytea NOT NULL,                  -- sealed
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (user_id, name)
);

CREATE TABLE oauth_metadata (
  url        text PRIMARY KEY,                -- document URL actually fetched
  kind       text NOT NULL,                   -- 'prm' | 'as'
  document   bytea NOT NULL,
  fetched_at timestamptz NOT NULL
);
